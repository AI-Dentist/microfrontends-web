import { buildRequestHeaders, isTrustedApiUrl, resolveIdempotencyKey } from './request-headers';

describe('buildRequestHeaders', () => {
  it('sends the Keycloak token as a bearer and no dev user header', () => {
    expect(buildRequestHeaders({ token: 'jwt-123', devUser: 'admin-scz' })).toEqual({
      Authorization: 'Bearer jwt-123',
    });
  });

  it('falls back to X-Dev-User when there is no token', () => {
    expect(buildRequestHeaders({ token: null, devUser: 'admin-scz' })).toEqual({
      'X-Dev-User': 'admin-scz',
    });
  });

  it('sends no identity headers without token or dev user', () => {
    expect(buildRequestHeaders({ token: null, devUser: null })).toEqual({});
  });

  it('adds the Idempotency-Key header when provided', () => {
    expect(buildRequestHeaders({ token: 't', devUser: null, idempotencyKey: 'key-1' })).toEqual({
      Authorization: 'Bearer t',
      'Idempotency-Key': 'key-1',
    });
  });
});

describe('isTrustedApiUrl', () => {
  const bases = ['http://localhost:8080/graphql', 'http://localhost:8080/api/v1'];
  const origin = 'http://localhost:4201';

  it('trusts URLs on the MS1 origin', () => {
    expect(isTrustedApiUrl('http://localhost:8080/api/v1/reportes/9.xlsx', bases, origin)).toBe(true);
  });

  it('trusts relative URLs when the API is served from the current origin', () => {
    expect(isTrustedApiUrl('/api/v1/recibos/1/pdf', ['/graphql'], 'https://erp.clinica.bo')).toBe(true);
  });

  it('does not trust other hosts, so the token is never sent there', () => {
    expect(isTrustedApiUrl('https://cdn.example.com/a.pdf', bases, origin)).toBe(false);
    expect(isTrustedApiUrl('http://localhost:9999/a.pdf', bases, origin)).toBe(false);
  });

  it('does not trust non-http schemes', () => {
    expect(isTrustedApiUrl('javascript:alert(1)', bases, origin)).toBe(false);
  });
});

describe('resolveIdempotencyKey', () => {
  const factory = () => 'generated-uuid';

  it('reuses the key generated by the form for a mutation', () => {
    expect(resolveIdempotencyKey('mutation', 'form-key', factory)).toBe('form-key');
  });

  it('generates a key for a mutation without one', () => {
    expect(resolveIdempotencyKey('mutation', undefined, factory)).toBe('generated-uuid');
  });

  it('never sends a key for queries', () => {
    expect(resolveIdempotencyKey('query', 'form-key', factory)).toBeUndefined();
  });
});
